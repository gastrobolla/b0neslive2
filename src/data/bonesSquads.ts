// Flat liste over alle reelle spillere i klubben
export const ALL_BONES_PLAYERS: Player[] = ALL_BONES_SQUADS.flatMap((squad) => squad.players);

// Hjelpefunksjon for å hente tropp for et bestemt lag
export function getSquadForTeam(teamId: string): TeamSquad | undefined {
  return ALL_BONES_SQUADS.find((s) => s.teamId === teamId);
}

// Hjelpefunksjon for å hente kamptropp (startellever og innbyttere)
export function getMatchLineup(teamId: string): MatchLineup | undefined {
  const squad = getSquadForTeam(teamId);
  if (!squad) return undefined;

  const starters = squad.players.filter((p) => p.isStarter);
  const bench = squad.players.filter((p) => !p.isStarter);

  return {
    formation: squad.formation,
    coach: squad.coach,
    teamName: squad.teamName,
    starters,
    bench,
  };
}
